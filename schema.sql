-- Lumé Beauty & Spa: Supabase starter schema
-- Run in Supabase SQL Editor on a NEW project after reviewing the policies.
create extension if not exists pgcrypto;

create table if not exists public.salons (
  id uuid primary key default gen_random_uuid(),
  name text not null default 'Beauty & Spa',
  slug text unique,
  logo_url text,
  phone text,
  whatsapp text,
  email text,
  instagram_url text,
  facebook_url text,
  tiktok_url text,
  primary_color text not null default '#d96e89',
  seo_title text,
  seo_description text,
  currency text not null default 'MAD',
  delivery_fee numeric(12,2) not null default 25 check (delivery_fee >= 0),
  payment_methods text[] not null default array['cod'],
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.salon_members (
  salon_id uuid not null references public.salons(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'owner' check (role in ('owner','manager','staff')),
  created_at timestamptz not null default now(),
  primary key (salon_id, user_id)
);

create table if not exists public.services (
  id uuid primary key default gen_random_uuid(),
  salon_id uuid not null references public.salons(id) on delete cascade,
  name text not null,
  description text,
  price numeric(12,2) not null default 0 check (price >= 0),
  duration_minutes integer not null default 60 check (duration_minutes > 0),
  image_url text,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  salon_id uuid not null references public.salons(id) on delete cascade,
  name text not null,
  slug text,
  description text,
  price numeric(12,2) not null default 0 check (price >= 0),
  compare_at_price numeric(12,2) check (compare_at_price is null or compare_at_price >= price),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  image_url text,
  is_active boolean not null default true,
  is_featured boolean not null default false,
  seo_title text,
  seo_description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (salon_id, slug)
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  salon_id uuid not null references public.salons(id) on delete cascade,
  order_number bigint generated by default as identity,
  customer_name text not null,
  customer_phone text not null,
  customer_email text,
  shipping_city text,
  shipping_address text not null,
  notes text,
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  delivery_fee numeric(12,2) not null default 0 check (delivery_fee >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  payment_method text not null default 'cod' check (payment_method in ('cod','bank_transfer')),
  payment_status text not null default 'unpaid' check (payment_status in ('unpaid','paid','refunded')),
  status text not null default 'pending' check (status in ('pending','confirmed','processing','shipped','delivered','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(12,2) generated always as (unit_price * quantity) stored
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  salon_id uuid not null references public.salons(id) on delete cascade,
  service_id uuid references public.services(id) on delete set null,
  service_name text not null,
  customer_name text not null,
  customer_phone text not null,
  customer_email text,
  requested_at timestamptz not null,
  notes text,
  status text not null default 'pending' check (status in ('pending','confirmed','completed','cancelled','no_show')),
  internal_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.expenses (
  id uuid primary key default gen_random_uuid(),
  salon_id uuid not null references public.salons(id) on delete cascade,
  title text not null,
  category text not null default 'other',
  amount numeric(12,2) not null check (amount >= 0),
  expense_date date not null default current_date,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id uuid primary key default gen_random_uuid(),
  salon_id uuid not null references public.salons(id) on delete cascade,
  title text not null,
  slug text not null,
  excerpt text,
  content text not null default '',
  cover_image_url text,
  seo_title text,
  seo_description text,
  status text not null default 'draft' check (status in ('draft','published')),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (salon_id, slug)
);

create table if not exists public.coupons (
  id uuid primary key default gen_random_uuid(),
  salon_id uuid not null references public.salons(id) on delete cascade,
  code text not null,
  discount_percent integer not null check (discount_percent between 1 and 90),
  starts_at timestamptz,
  expires_at timestamptz,
  max_uses integer,
  uses_count integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (salon_id, code)
);

create index if not exists idx_products_salon_active on public.products(salon_id, is_active);
create index if not exists idx_services_salon_active on public.services(salon_id, is_active);
create index if not exists idx_orders_salon_created on public.orders(salon_id, created_at desc);
create index if not exists idx_bookings_salon_date on public.bookings(salon_id, requested_at);
create index if not exists idx_posts_published on public.posts(salon_id, status, published_at desc);
create index if not exists idx_expenses_salon_date on public.expenses(salon_id, expense_date desc);

create or replace function public.is_salon_member(target_salon uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.salon_members m
    where m.salon_id = target_salon and m.user_id = auth.uid()
  );
$$;

create or replace function public.is_salon_manager(target_salon uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.salon_members m
    where m.salon_id = target_salon and m.user_id = auth.uid()
      and m.role in ('owner','manager')
  );
$$;


-- Salon public profile can be read publicly; only members can edit.
drop policy if exists "salons public read" on public.salons;
create policy "salons public read" on public.salons for select using (true);
drop policy if exists "salons members update" on public.salons;
create policy "salons members update" on public.salons for update using (public.is_salon_manager(id)) with check (public.is_salon_manager(id));
drop policy if exists "salon owner insert" on public.salons;
create policy "salon owner insert" on public.salons for insert with check (auth.uid() is not null);

drop policy if exists "members read members" on public.salon_members;
create policy "members read members" on public.salon_members for select using (public.is_salon_member(salon_id));
-- Create initial owner membership manually in SQL Editor using the authenticated user's UUID.
drop policy if exists "managers manage memberships" on public.salon_members;
create policy "managers manage memberships" on public.salon_members for all using (public.is_salon_manager(salon_id)) with check (public.is_salon_manager(salon_id));

drop policy if exists "public read active services" on public.services;
create policy "public read active services" on public.services for select using (is_active or public.is_salon_member(salon_id));
drop policy if exists "members manage services" on public.services;
create policy "members manage services" on public.services for all using (public.is_salon_member(salon_id)) with check (public.is_salon_member(salon_id));

drop policy if exists "public read active products" on public.products;
create policy "public read active products" on public.products for select using (is_active or public.is_salon_member(salon_id));
drop policy if exists "members manage products" on public.products;
create policy "members manage products" on public.products for all using (public.is_salon_member(salon_id)) with check (public.is_salon_member(salon_id));

-- IMPORTANT: Public checkout should be implemented through a validated Edge Function.
-- Do not enable anonymous direct INSERT into orders/order_items: otherwise clients can spoof prices.
drop policy if exists "members manage orders" on public.orders;
create policy "members manage orders" on public.orders for all using (public.is_salon_member(salon_id)) with check (public.is_salon_member(salon_id));
drop policy if exists "members manage order items" on public.order_items;
create policy "members manage order items" on public.order_items for all
using (exists (select 1 from public.orders o where o.id = order_id and public.is_salon_member(o.salon_id)))
with check (exists (select 1 from public.orders o where o.id = order_id and public.is_salon_member(o.salon_id)));

-- Public booking submission also belongs behind an Edge Function to rate-limit and validate input.
drop policy if exists "members manage bookings" on public.bookings;
create policy "members manage bookings" on public.bookings for all using (public.is_salon_member(salon_id)) with check (public.is_salon_member(salon_id));

drop policy if exists "members manage expenses" on public.expenses;
create policy "members manage expenses" on public.expenses for all using (public.is_salon_member(salon_id)) with check (public.is_salon_member(salon_id));

drop policy if exists "public read published posts" on public.posts;
create policy "public read published posts" on public.posts for select using (status = 'published' or public.is_salon_member(salon_id));
drop policy if exists "members manage posts" on public.posts;
create policy "members manage posts" on public.posts for all using (public.is_salon_member(salon_id)) with check (public.is_salon_member(salon_id));

drop policy if exists "public read active coupons" on public.coupons;
create policy "public read active coupons" on public.coupons for select using (is_active);
drop policy if exists "members manage coupons" on public.coupons;
create policy "members manage coupons" on public.coupons for all using (public.is_salon_member(salon_id)) with check (public.is_salon_member(salon_id));

